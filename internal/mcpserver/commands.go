// commands generates harness-native entry points (slash commands / prompt
// files / AGENTS.md sections) from the two templates below, so every
// supported coding-agent harness gets the same two-mode ($ARGUMENTS empty =
// state snapshot, non-empty = full SDD lifecycle) dispatch that
// .claude/commands/spectackle.md pioneered — without hand-maintaining N
// per-harness copies. detect: sniff which harnesses are already wired into
// the repo from filesystem markers. gen: (re)write the dialect files for a
// harness set resolved arg > detection > elicitation (MCP-003 family): the
// user answers a native checkbox form, or — no UI, decline, or a different
// harness — an `adr` item is minted and left open exactly like
// decideAsk (decide.go), never blocking the caller.
//
// gen's command set defaults to the three load-bearing commands (entry
// point, state, generate) — enough to run the lifecycle and to ask for more.
// The six exploration commands (find, get, research, swarm, export, merge)
// are opt-in: pass all=true for every command, or commands=<names> for a
// specific subset (either unions with the default three, never replaces
// them — the default set is always present once requested at all).
type commandsIn struct {
	Op       string   `json:"op" jsonschema:"detect|gen|install-hooks"`
	Harness  []string `json:"harness,omitempty" jsonschema:"claude|copilot|codex|kimi — omit to auto-detect"`
	Commands []string `json:"commands,omitempty" jsonschema:"gen only: opt-in command names to add on top of the default three (find|get|research|swarm|export|merge) — omit for defaults only"`
	All      bool     `json:"all,omitempty" jsonschema:"gen only: generate every command (default three plus all six opt-in exploration commands)"`
}

//go:embed templates/commands/*.tmpl
var commandTemplateFS embed.FS

// commandTemplates parses once at package init: a bad embedded template is a
// build-time bug, not a runtime one.
var commandTemplates = template.Must(template.ParseFS(commandTemplateFS, "templates/commands/*.tmpl"))

//go:embed templates/hooks/*.tmpl
var hookTemplateFS embed.FS

// hookTemplates parses once at package init, same reasoning as
// commandTemplates: a bad embedded hook template is a build-time bug.
var hookTemplates = template.Must(template.ParseFS(hookTemplateFS, "templates/hooks/*.tmpl"))

// commandsData is the template data — {Binary, Tool} are both "spectackle"
// today; kept as two fields (not one) because the binary name (CLI, `/x-state`
// slash-command stem) and the MCP tool/server name are conceptually distinct
// even though this repo's install happens to give them the same value.
type commandsData struct {
	Binary string
	Tool   string
	// RepoURL is the module's https:// repository URL, derived the same way
	// the instructions manifest derives it (moduleRepoURL). Generated
	// slash-command surfaces are read by agents that never see the
	// initialize handshake, so the defect-report destination has to be named
	// here too rather than left as "its repository".
	RepoURL string
}

// generatedHeader is stamped into every artifact `commands gen` writes —
// hand-edits belong in the templates, not the generated files.
const generatedHeader = "<!-- generated by spectackle `commands` — edit internal/mcpserver/templates, not this file -->"

// hookGeneratedHeader is the POSIX-sh equivalent of generatedHeader (an
// HTML comment isn't valid shell) — the first line of the rendered
// pre-commit.tmpl body and the marker `install-hooks` checks for before
// ever overwriting a pre-existing hooks/pre-commit file: present means
// "ours, safe to regenerate"; absent means "the repo owner's, refuse".
const hookGeneratedHeader = "# generated by spectackle `commands install-hooks` — edit internal/mcpserver/templates/hooks, not this file"

// sectionBegin/sectionEnd delimit the managed block commands gen writes into
// AGENTS.md for the codex/kimi dialect — everything outside the markers is
// the repo owner's, never touched.
const (
	sectionBegin = "<!-- spectackle:commands:begin -->"
	sectionEnd   = "<!-- spectackle:commands:end -->"
)

var validHarnesses = map[string]bool{"claude": true, "copilot": true, "codex": true, "kimi": true}

// commandSpec describes one generated command. Name is the slash-command
// stem after the binary — empty for the main lifecycle entry point, which
// gets the bare "<binary>.md" filename instead of "<binary>-.md". Heading is
// the AGENTS.md managed-section heading word (codex/kimi dialect); it
// mirrors Name except for the entry point, which keeps the historical
// "workflow" heading. Description is the claude dialect's frontmatter
// `description:` line and doubles as the copilot dialect's doc comment.
// Default marks the load-bearing commands `gen` emits without an explicit
// all=/commands= argument: the entry point, state, and generate itself —
// generate must be default, otherwise a user with only the default set has
// no way to ask for the rest short of reading source.
type commandSpec struct {
	Name        string
	Heading     string
	Template    string
	Description string
	Default     bool
}

// commandSpecs is the full generated-command set, in the order every
// dialect writer emits them. Adding a command means: one new template file
// under templates/commands, one entry here — nothing else changes.
